import assert from "node:assert/strict";
export async function workLabAuthorRegression({ page, api, password1, password2 }) {
  const button = name => page.getByRole("button", { name, exact: true });
  const label = name => page.getByLabel(name, { exact: true });
  await page.setViewportSize({ width: 1440, height: 1080 });
  await button("作者模式").click();
  const status = await (await fetch(api.url + "/api/status")).json();
  password1 ||= crypto.randomUUID() + "-first";
  password2 ||= crypto.randomUUID() + "-second";
  await label("第一組密碼").fill(password1);
  await label("第二組密碼").fill(password2);
  await button(status.setupAvailable ? "設定並進入編輯" : "進入作者模式").click();
  await label("預覽頁面").selectOption("work");
  const root = page.locator(".editor-canvas [data-work-lab]");
  await root.locator('.lab-stage[data-ready="true"]').waitFor();
  assert.ok(await root.locator("[data-element-key]").count() >= 60, "The complete page exposes internal editable layers");
  await label("封面貼合比例").fill("0.58");
  await label("相機跟隨速度").fill("32");
  await label("陣列相機距離倍率").fill("0.55");
  await label("移動前方波動距離").fill("8");
  await label("卡帶本體").fill("#b5c9bc");
  await page.waitForFunction(() => document.querySelector('.editor-canvas .lab-stage')?.dataset.coverScale === "0.58");
  await button("復原上一步").click();
  await page.waitForFunction(() => document.querySelector('.editor-canvas .lab-stage')?.dataset.cassetteColor === "#e1dcd1");
  await button("重做").click();
  await button("資料預覽").click();
  await page.waitForFunction(() => document.querySelector('.editor-canvas [data-work-lab]')?.dataset.mode === "detail");
  await button("陣列預覽").click();
  await root.locator('[data-copy-key="lab.menu"]').click();
  await label("介面文字內容").fill("探索導航");
  await page.getByText("所有修改已儲存", { exact: true }).waitFor();
  await page.screenshot({ path: "artifacts/work-author-layers.png" });
  const draft = await api.store.getDraft();
  assert.equal(draft.content.workLab.parameters.coverScale, .58);
  assert.equal(draft.content.workLab.parameters.cameraFollow, 32);
  assert.equal(draft.content.workLab.parameters.cameraDistance, .55);
  assert.equal(draft.content.workLab.parameters.waveLead, 8);
  assert.equal(draft.content.workLab.palette.shell, "#b5c9bc");
  assert.equal(draft.content.presentation.copy["lab.menu"], "探索導航");
  await label("切換模式").selectOption("blocks");
  const mini = page.frameLocator('iframe[title="積木即時預覽"]');
  await mini.locator('[data-lab-render-snapshot][data-ready="true"]').waitFor();
  await mini.locator('[data-lab-render-snapshot]').evaluate(image => image.decode());
  await page.getByRole("tab", { name: "作品展示", exact: true }).click();
  assert.equal(await page.locator(".library-scratch-block").count(), 5);
  await page.getByRole("tab", { name: "物件圖層", exact: true }).click();
  await label("腳本目標物件").selectOption("projects");
  await button("物件圖層 · 指定既有內容").dragTo(page.locator(".scratch-plane"), { targetPosition: { x: 40, y: 50 } });
  const stack = page.locator(".scratch-stack").last();
  await stack.locator(".scratch-object").dblclick();
  await label("修改觸發事件").selectOption("load");
  await button("完成").click();
  await page.getByRole("tab", { name: "作品展示", exact: true }).click();
  await page.getByRole("button", { name: /^設定作品動態參數/ }).dragTo(stack.locator(".logic-drop-slot").first());
  await stack.getByRole("group", { name: "編輯積木：設定作品動態參數", exact: true }).dblclick();
  await label("作品展示控制項").selectOption("cameraFollow");
  await label("作品動態參數值").fill("38");
  await button("完成").click();
  await page.getByText("所有修改已儲存", { exact: true }).waitFor();
  await page.screenshot({ path: "artifacts/work-author-blocks.png" });
  await page.getByRole("button", { name: /執行預覽/ }).click();
  await page.waitForFunction(() => document.querySelector('.logic-live-preview .lab-stage')?.dataset.cameraFollow === "38");
  await button("關閉積木視窗").click();
  await label("切換模式").selectOption("layers");
  await button("發布").click();
  await button("確認發布").click();
  await page.getByText("已發布至本機預覽，關閉編輯器後可查看。", { exact: true }).waitFor();
  const published = await (await fetch(api.url + "/api/public")).json();
  assert.equal(published.content.workLab.parameters.cameraFollow, 32);
  assert.equal(published.content.workLab.palette.shell, "#b5c9bc");
  assert.equal(published.content.workspace.scripts.at(-1).blocks[0].amount, 38);
  await page.evaluate(() => { localStorage.setItem("outdesign.site.theme.v1", "dark"); localStorage.setItem("outdesign.work-lab.preferences.v2", JSON.stringify({ theme: "dark", motionPreset: "system", effects: { boot: false } })); });
  await Promise.all([page.waitForEvent("load"), button("登出並關閉編輯器").click()]);
  await page.waitForFunction(() => document.querySelector('.lab-stage')?.dataset.cameraFollow === "38");
  assert.equal(await page.locator('[data-work-lab]').getAttribute("data-theme"), "dark", "A camera parameter block preserves the visitor's chosen theme");
  assert.equal(await page.locator('[data-copy-key="lab.menu"]').textContent(), "探索導航");
  assert.equal(await page.locator('.lab-header nav > [data-menu-toggle]').count(), 1);
}
